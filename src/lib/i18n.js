export function translate(lang, key, vars) {
  const lookup = (dict) => key.split(".").reduce((node, part) => node?.[part], dict);
  let text = lookup(STRINGS[lang]) ?? lookup(STRINGS.en) ?? key;
  if (typeof text === "string" && vars) {
    text = text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
  }
  return text;
}

export function detectLang() {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  return langs.some((l) => l?.toLowerCase().startsWith("az")) ? "az" : "en";
}
